// Generates the fixture :astronomy's sun-time test checks against: NOAA's published sunrise and
// sunset times, from the yearly tables of the NOAA Global Monitoring Laboratory solar
// calculator, for a spread of latitudes.
//
//   node tools/astronomy/noaa-sun-fixture.mjs
//
// Run it from the repository root. It fetches one page per place and rewrites one file. NOAA
// writes times in the place's local time, to the minute, and "00:00" on a day with no sunrise or
// no sunset; the fixture records those as "none". Each day carries the place's UTC offset at
// noon, from this Node runtime's time-zone data, so the test needs no time-zone database.
import { writeFileSync } from "node:fs";

const YEAR = 2024;
const PLACES = [
  ["Toronto", 43.6532, -79.3832],
  ["Reykjavik", 64.1466, -21.9426],
  ["Tromso", 69.6492, 18.9553],
  ["Quito", -0.1807, -78.4678],
  ["Singapore", 1.3521, 103.8198],
  ["Sydney", -33.8688, 151.2093],
  ["Cape Town", -33.9249, 18.4241],
  ["Honolulu", 21.3069, -157.8583],
];

const cells = (row) => [...row.matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/g)].map((m) => m[1].replace(/<[^>]+>/g, "").trim());
function table(page, title) {
  const start = page.indexOf(title);
  const end = page.indexOf("</table>", start);
  const rows = [...page.slice(start, end).matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/g)].map((m) => cells(m[1]));
  return rows.filter((r) => /^\d+$/.test(r[0]));
}

/** The UTC offset, in minutes, of [zone] at noon local time on [iso]. */
function offsetMinutes(zone, iso) {
  const noonUtc = new Date(`${iso}T12:00:00Z`);
  const part = new Intl.DateTimeFormat("en", { timeZone: zone, timeZoneName: "longOffset" })
    .formatToParts(noonUtc).find((p) => p.type === "timeZoneName").value; // "GMT-04:00", or "GMT"
  const m = part.match(/GMT([+-])(\d{2}):(\d{2})/);
  return m ? (m[1] === "-" ? -1 : 1) * (Number(m[2]) * 60 + Number(m[3])) : 0;
}

const lines = [];
for (const [name, lat, lon] of PLACES) {
  const page = await (await fetch(`https://gml.noaa.gov/grad/solcalc/table.php?lat=${lat}&lon=${lon}&year=${YEAR}`)).text();
  const zone = page.match(/Time Zone Offset:\s*([A-Za-z_\/]+)/)[1];
  const rise = table(page, "Sunrise Table");
  const set = table(page, "Sunset Table");
  for (let month = 1; month <= 12; month++) {
    for (const [i, row] of rise.entries()) {
      const day = Number(row[0]);
      const r = row[month], s = set[i][month];
      if (!r) continue; // no such day in this month
      const iso = `${YEAR}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
      const none = (t) => (t === "00:00" ? "none" : t);
      lines.push([name, lat, lon, iso, offsetMinutes(zone, iso), none(r), none(s)].join("|"));
    }
  }
}

const out = `package io.github.aughtone.astronomy

// ─────────────────────────────────────────────────────────────────────────────
// Generated by tools/astronomy/noaa-sun-fixture.mjs from the NOAA Global Monitoring Laboratory
// solar calculator's ${YEAR} sunrise and sunset tables — do not edit by hand.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * NOAA's sunrise and sunset for every day of ${YEAR} at a spread of places, one case per line as
 * \`place|latitude|longitude|date|offset|sunrise|sunset\`: the offset is the place's UTC offset
 * that day in minutes, and the times are local, to the minute, or \`none\` on a day the sun does
 * not rise or does not set.
 */
internal val noaaSunFixture: String = """
${lines.join("\n")}
"""
`;
const path = "astronomy/src/commonTest/kotlin/io/github/aughtone/astronomy/NoaaSunFixture.kt";
writeFileSync(path, out);
console.log(`${lines.length} days for ${PLACES.length} places, wrote ${path} (${out.length} characters)`);
