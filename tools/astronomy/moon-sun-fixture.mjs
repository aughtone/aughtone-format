// Generates the fixture :astronomy's moon and solar-term tests check against: new and full moons
// from NASA's "Phases of the Moon: 2001 to 2100" table (Espenak, GSFC) for 2001 to 2030, and the
// 24 solar terms from the Hong Kong Observatory's yearly solar-term data, for the years in that
// range the Observatory publishes.
//
//   node tools/astronomy/moon-sun-fixture.mjs
//
// Run it from the repository root. It fetches the pages and rewrites one file. Both sources give
// times to the minute: NASA in Universal Time, the Observatory in Hong Kong Time (UTC+8), which
// is converted to UTC here.
import { writeFileSync } from "node:fs";

const FIRST = 2001, LAST = 2030;
const MONTHS = { Jan: 1, Feb: 2, Mar: 3, Apr: 4, May: 5, Jun: 6, Jul: 7, Aug: 8, Sep: 9, Oct: 10, Nov: 11, Dec: 12 };
const pad = (n) => String(n).padStart(2, "0");
const lines = [];

// NASA: fixed-width rows, with New Moon, First Quarter, Full Moon and Last Quarter entries
// starting at columns 8, 26, 44 and 62.
const html = await (await fetch("https://eclipse.gsfc.nasa.gov/phase/phases2001.html")).text();
const text = html.replace(/<[^>]+>/g, "").replace(/&[a-z]+;/g, " ");
const COLUMN_KINDS = ["new", null, "full", null];
let year = null;
for (const line of text.split("\n")) {
  const y = line.match(/^\s*(\d{4})\s/);
  if (y) year = Number(y[1]);
  if (year === null || year < FIRST || year > LAST) continue;
  for (const m of line.matchAll(/(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\s+(\d{1,2})\s+(\d{2}):(\d{2})/g)) {
    const column = Math.round((m.index - 8) / 18);
    const kind = COLUMN_KINDS[column];
    if (!kind || Math.abs(m.index - (8 + 18 * column)) > 2) continue;
    lines.push(`${kind}||${year}-${pad(MONTHS[m[1]])}-${pad(m[2])}T${m[3]}:${m[4]}:00Z`);
  }
}

// Hong Kong Observatory: 24 terms a year in order from Minor Cold (285°) in early January. It
// publishes the files for recent years only; the years it has within the range are used.
const termYears = [];
for (let y = FIRST; y <= LAST; y++) {
  const response = await fetch(`https://www.hko.gov.hk/en/gts/astronomy/data/files/24SolarTerms_${y}.xml`);
  if (!response.ok) continue;
  termYears.push(y);
  const xml = await response.text();
  const terms = [...xml.matchAll(/<M>(\d+)<\/M><D>(\d+)<\/D><hm>(\d+):(\d+)<\/hm>/g)];
  if (terms.length !== 24) throw new Error(`${y}: ${terms.length} solar terms`);
  terms.forEach((t, i) => {
    const longitude = (285 + 15 * i) % 360;
    const utc = new Date(Date.UTC(y, Number(t[1]) - 1, Number(t[2]), Number(t[3]) - 8, Number(t[4])));
    lines.push(`term|${longitude}|${utc.toISOString().replace(".000", "")}`);
  });
}

const counts = Object.fromEntries(["new", "full", "term"].map((k) => [k, lines.filter((l) => l.startsWith(k)).length]));
const out = `package io.github.aughtone.astronomy

// ─────────────────────────────────────────────────────────────────────────────
// Generated by tools/astronomy/moon-sun-fixture.mjs — do not edit by hand. New and full moons
// from NASA's "Phases of the Moon: 2001 to 2100" (Espenak, GSFC); solar terms from the Hong Kong
// Observatory's yearly solar-term data. Moon phases ${FIRST} to ${LAST}; solar terms
// ${termYears[0]} to ${termYears[termYears.length - 1]}, the years the Observatory publishes.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Published moon phases and solar terms, one per line as \`kind|longitude|instant\`: kind is
 * \`new\` or \`full\` (no longitude) or \`term\` (the sun's apparent longitude, a multiple of 15°),
 * and the instant is UTC, to the minute.
 */
internal val moonSunFixture: String = """
${lines.join("\n")}
"""
`;
const path = "astronomy/src/commonTest/kotlin/io/github/aughtone/astronomy/MoonSunFixture.kt";
writeFileSync(path, out);
if (termYears.length < 8) throw new Error(`solar terms for only ${termYears.length} years`);
console.log(`${JSON.stringify(counts)}, solar terms ${termYears[0]}-${termYears[termYears.length - 1]}, wrote ${path} (${out.length} characters)`);
